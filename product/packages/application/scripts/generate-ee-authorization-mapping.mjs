import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";

// A new matrix revision must use new release IDs; never edit a shipped release.
const tools = [
  ["ee.list_projects", "page:projects", "read"], ["ee.get_project_context", "page:projects", "read"],
  ["ee.list_requirements", "page:requirements", "read"], ["ee.list_functions", "page:functions", "read"],
  ["ee.get_function_ssts_matrix", "page:functions", "read"], ["ee.get_traceability_stats", "page:functions", "read"],
  ["ee.list_ssts", "page:architecture", "read"], ["ee.get_ssts", "page:architecture", "read"],
  ["ee.submit_ssts_review", "page:architecture", "edit"], ["ee.create_ssts_candidate", "page:architecture", "edit"],
  ["ee.decide_ssts_review", "page:architecture", "review"]
];
const reads = tools.filter(([, , operation]) => operation === "read").map(([name]) => name);
const aliases = [
  ...["projects", "requirements", "functions", "architecture"].map(page => [`page:${page}`, `page:${page}`, "read", tools.filter(([, permission, operation]) => permission === `page:${page}` && operation === "read").map(([name]) => name)]),
  ["draft.read", "page:architecture", "read", reads], ["draft.generate", "page:architecture", "read", reads],
  ["ee.ssts.review.request", "page:architecture", "edit", tools.filter(([, , operation]) => operation !== "read").map(([name]) => name)],
  ["approval.decide", "page:architecture", "review", tools.filter(([, , operation]) => operation !== "read").map(([name]) => name)],
  ["project.read", "page:projects", "read", ["ee.get_project_context", "ee.list_projects"]],
  ["requirement.read", "page:requirements", "read", ["ee.list_requirements"]],
  ["function.read", "page:functions", "read", ["ee.list_functions", "ee.get_function_ssts_matrix", "ee.get_traceability_stats"]],
  ["ssts.read", "page:architecture", "read", ["ee.list_ssts", "ee.get_ssts"]],
  ["ssts.generate", "page:architecture", "read", reads],
  ["ssts.review.request", "page:architecture", "edit", ["ee.submit_ssts_review"]],
  ["ssts.review.decide", "page:architecture", "review", ["ee.decide_ssts_review"]],
  ...tools.map(([name, page, operation]) => ["tool.execute", page, operation, [name]])
];
const canonical = value => value === null || typeof value !== "object" ? JSON.stringify(value)
  : Array.isArray(value) ? `[${value.map(canonical).join(",")}]`
    : `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonical(value[key])}`).join(",")}}`;
const releases = aliases.map(([action, page, operation, toolKeys]) => {
  const value = { contract_name: "pc.provider-compatibility-mapping/1", contract_version: 1,
    mapping_release_id: `mapping:ee-v1:mvp-1:${action}${action === "tool.execute" ? `:${toolKeys[0]}` : ""}`,
    provider_registration_id: "provider:eeclaw", provider_type: "eeclaw", compatibility_version: "ee-v1",
    pc_action_pattern: action, resource_authority: "eeclaw",
    provider_permission_mapping: { permission_keys: [page], baseline_page_keys_version: "BASELINE_PAGE_KEYS_V1" },
    provider_action_mapping: { action_keys: [operation] }, provider_tool_mapping: { tool_keys: toolKeys },
    decision_mode: "PC_AND_PROVIDER", status: "ACTIVE", effective_from: "2026-11-23T00:00:00.000Z" };
  return { ...value, artifact_digest: `sha256:${createHash("sha256").update(canonical(value)).digest("hex")}` };
});
const directory = new URL("../fixtures/", import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL("ee-v1-mapping-release.json", directory), `${JSON.stringify(releases, null, 2)}\n`);
await writeFile(new URL("../src/ee-v1-mappings.generated.ts", import.meta.url),
  `// Generated by scripts/generate-ee-authorization-mapping.mjs.\nimport type { ProviderCompatibilityMapping } from "./compatibility-mapping.js";\nexport const EE_V1_MAPPING_RELEASES: readonly ProviderCompatibilityMapping[] = ${JSON.stringify(releases, null, 2)};\n`);
console.log(`Generated ${releases.length} immutable EE V1 mapping releases.`);
